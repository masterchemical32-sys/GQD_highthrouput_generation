from rdkit import Chem

def fuse_true(mol1, mol2):
    pairs1 = get_edge_pairs(mol1)
    pairs2 = get_edge_pairs(mol2)

    if not pairs1 or not pairs2:
        return None

    a1, b1 = random.choice(pairs1)
    a2, b2 = random.choice(pairs2)

    mol1 = Chem.RWMol(mol1)
    mol2 = Chem.RWMol(mol2)

    # --- Step 1: combine
    combo = Chem.CombineMols(mol1, mol2)
    rw = Chem.RWMol(combo)

    offset = mol1.GetNumAtoms()
    a2_off = a2 + offset
    b2_off = b2 + offset

    try:
        # --- Step 2: get neighbors of atoms to delete (excluding each other)
        nbrs_a2 = [n.GetIdx() for n in rw.GetAtomWithIdx(a2_off).GetNeighbors() if n.GetIdx() != b2_off]
        nbrs_b2 = [n.GetIdx() for n in rw.GetAtomWithIdx(b2_off).GetNeighbors() if n.GetIdx() != a2_off]

        # --- Step 3: reconnect neighbors to mol1 atoms
        for n in nbrs_a2:
            rw.AddBond(a1, n, Chem.BondType.AROMATIC)

        for n in nbrs_b2:
            rw.AddBond(b1, n, Chem.BondType.AROMATIC)

        # --- Step 4: REMOVE the two atoms (IMPORTANT: remove higher index first)
        for idx in sorted([a2_off, b2_off], reverse=True):
            rw.RemoveAtom(idx)

        mol = rw.GetMol()

        # --- Step 5: sanitize
        if not safe_sanitize(mol):
            return None

        return mol

    except:
        return None

