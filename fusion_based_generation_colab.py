generated_smiles = set()
generated_molecules = []

attempts = 0

while len(generated_smiles) < target and attempts < max_attempts:
    attempts += 1

    mol1, mol2 = random.sample(fragments, 2)

    # 🔥 TRUE fusion
    combined = fuse_true(mol1, mol2)
    if combined is None:
        continue

    # size filter
    if combined.GetNumAtoms() > 120 or combined.GetNumAtoms() < 10:
        continue

    # ---------------------------
    # FINAL VALIDITY CHECK
    # ---------------------------
    try:
        Chem.SanitizeMol(combined)
    except:
        continue

    smi = Chem.MolToSmiles(combined, canonical=True)

    if not smi or len(smi) < 5:
        continue

    if smi in generated_smiles:
        continue

    generated_smiles.add(smi)
    generated_molecules.append(combined)

    if len(generated_smiles) % 500 == 0:
        print(f"Generated: {len(generated_smiles)}")

