# ---- Find valid aromatic edge pairs ----
def get_edge_pairs(mol):
    pairs = []
    for bond in mol.GetBonds():
        a1 = bond.GetBeginAtom()
        a2 = bond.GetEndAtom()

        if (
            a1.GetAtomicNum() == 6 and
            a2.GetAtomicNum() == 6 and
            a1.GetIsAromatic() and
            a2.GetIsAromatic() and
            a1.GetDegree() == 2 and
            a2.GetDegree() == 2
        ):
            pairs.append((a1.GetIdx(), a2.GetIdx()))
    return pairs


